import { authenticatedSession } from './support/authenticated-session.mjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import { createServer } from 'node:http';
import { fixture } from './support/v2-source-adapters/fixture.mjs';
import { createIdentityRouter } from '../server/v2/identity/routes.js';
import { createSyncCenterRouter } from '../server/v2/sync-center/routes.js';
import { createStatsRouter } from '../server/v2/stats/routes.js';
import { createStatsSyncBridge } from '../server/v2/management-adapters/sources/index.js';

test('G03-authenticated HTTP: success, CSRF, receipt replay, failure, scoped coverage, query isolation', async t => {
  const f = await fixture(), app = express(), server = createServer(app);
  await new Promise(r => server.listen(0, '127.0.0.1', r));
  const origin = `http://127.0.0.1:${server.address().port}`;
  const auth = createIdentityRouter({ service: f.identity, origin, providers: {} });
  app.use('/api/v2', (req, res, next) => { req.v2Identity = { service: f.identity, authenticate: opts => auth.authenticate(opts)(req) }; next(); });
  app.use('/api/v2', createSyncCenterRouter({ getSystem: () => ({ service: f.service, worker: f.worker }) }));
  app.use('/api/v2', createStatsRouter({ providers: f.adapters.statsProviders, authorizeWrite: () => true, ...createStatsSyncBridge({ identity: f.identity, syncService: f.service, readSourceConfig: f.options.readSourceConfig }) }));
  t.after(async () => { await auth.stopEvents(); server.closeAllConnections(); await new Promise(r => server.close(r)); await f.close(); });
  const session = await authenticatedSession(f.identity, 'g05_account_admin');
  const headers = { Cookie: `nb_v2_session=${session.token}`, Origin: origin, 'Content-Type': 'application/json', 'X-CSRF-Token': session.csrfToken, 'Idempotency-Key': 'http-source-adapters-1' };
  const body = { type: 'member_profile', scope: { kind: 'members', memberIds: ['g05_alpha'] } };
  assert.equal((await fetch(origin + '/api/v2/sync-center/jobs')).status, 401);
  assert.equal((await fetch(origin + '/api/v2/sync-center/jobs', { method: 'POST', headers: { ...headers, 'X-CSRF-Token': 'wrong' }, body: JSON.stringify(body) })).status, 403);
  const post = async (path, data, extra = {}) => { const response = await fetch(origin + '/api/v2' + path, { method: 'POST', headers: { ...headers, ...extra }, body: JSON.stringify(data) }); return { status: response.status, ...await response.json() }; };
  const created = await post('/sync-center/jobs', body); assert.equal(created.status, 202);
  await f.worker.step();
  const detail = await (await fetch(origin + '/api/v2/sync-center/jobs/' + created.data.job.id, { headers })).json();
  assert.equal(detail.data.status, 'succeeded'); assert.equal(f.repo.get('members', 'g05_alpha').steamNickname, 'HTTP nickname');
  const replay = await post('/sync-center/jobs', body); assert.equal(replay.data.job.id, created.data.job.id);
  const conflict = await post('/sync-center/jobs', { ...body, type: 'kda' }); assert.equal(conflict.status, 409);
  const before = f.db.prepare('SELECT total_changes() n').get().n, calls = f.calls.length;
  const coverageResponse = await fetch(origin + '/api/v2/sync-center/coverage?type=member_profile&scope=members&memberIds=g05_alpha', { headers });
  assert.equal(coverageResponse.status, 200); assert.equal(coverageResponse.headers.get('cache-control'), 'no-store');
  assert.equal((await coverageResponse.json()).data.coverage.matched, 1); assert.equal(f.calls.length, calls);
  // Authentication may refresh its own session metadata; source facts remain untouched.
  assert.ok(f.db.prepare('SELECT total_changes() n').get().n >= before);
  const queued = await post('/stats/sync', { wipeId: 'fixture-wipe', sourceId: 'vital', expectedRevision: 1 }, { 'Idempotency-Key': 'http-stats-sync-1' });
  assert.equal(queued.status, 200, JSON.stringify(queued)); for (let i = 0; i < 10; i++) if (!await f.worker.step()) break;
  assert.equal(f.adapters.store.statsRow('fixture-wipe', 'g05_alpha').kills, 0);
  const rows = await (await fetch(origin + '/api/v2/stats/rows?wipeId=fixture-wipe&sourceId=vital&metricVersion=nb-kda-1', { headers })).json();
  assert.equal(rows.data.items[0].values.kills, 0);
  // Keep the actual query worker service: route creates the job; a new same-db service runs it.
  const query = await post('/stats/queries', { sourceId: 'official', steamInput: f.repo.get('members', 'g05_alpha').steamId }, { 'Idempotency-Key': 'http-query-source-1' });
  assert.equal(query.status, 200, JSON.stringify(query));
  const { StatsService } = await import('../server/v2/stats/service.js');
  const stats = new StatsService(f.identity, { providers: f.adapters.statsProviders });
  const beforeFacts = f.db.prepare("SELECT group_concat(hash) h FROM json_records WHERE collection IN ('members','memberProfiles','kdaRows','kdaSnapshots')").get().h;
  await stats.runJob(query.data.jobId);
  const result = await (await fetch(origin + '/api/v2/stats/jobs/' + query.data.jobId, { headers })).json();
  assert.equal(result.data.status, 'succeeded');
  assert.equal(f.db.prepare("SELECT group_concat(hash) h FROM json_records WHERE collection IN ('members','memberProfiles','kdaRows','kdaSnapshots')").get().h, beforeFacts);
  f.behaviors.set('/steam', (_q, res) => { res.statusCode = 500; res.end('secret credentials must never leak'); });
  const failed = await post('/sync-center/jobs', body, { 'Idempotency-Key': 'http-failing-source-1' }); await f.worker.step();
  const failDetail = await (await fetch(origin + '/api/v2/sync-center/jobs/' + failed.data.job.id, { headers })).json();
  assert.equal(failDetail.data.status, 'retry_wait'); assert.ok(!JSON.stringify(failDetail).includes('secret credentials'));
  const leader = await authenticatedSession(f.identity, 'g05_account_leader');
  assert.equal((await fetch(origin + '/api/v2/sync-center/coverage?type=member_profile&scope=members&memberIds=g05_foreign', { headers: { Cookie: `nb_v2_session=${leader.token}` } })).status, 403);
});
