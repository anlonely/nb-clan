function discordTextLanguage(language = DISCORD_DEFAULT_LANGUAGE) {
  const locale = normalizeText(language, 20).toLowerCase().replace('_', '-');
  if (locale.startsWith('zh')) return 'zh';
  const baseLanguage = locale.split('-')[0];
  return DISCORD_TEXT[baseLanguage] ? baseLanguage : DISCORD_DEFAULT_LANGUAGE;
}

function discordText(language, key, vars = {}) {
  const textLanguage = discordTextLanguage(language);
  const template = DISCORD_TEXT[textLanguage]?.[key] || DISCORD_TEXT.en[key] || key;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_match, name) => String(vars[name] ?? ''));
}

function discordRegistrationCardText(language, key, vars = {}) {
  const textLanguage = discordTextLanguage(language);
  const template = DISCORD_REGISTRATION_CARD_TEXT[textLanguage]?.[key] || DISCORD_REGISTRATION_CARD_TEXT.en[key] || key;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_match, name) => String(vars[name] ?? ''));
}

function discordVitalVipText(language, key, vars = {}) {
  const textLanguage = discordTextLanguage(language);
  const template = DISCORD_VITAL_VIP_TEXT[textLanguage]?.[key] || DISCORD_VITAL_VIP_TEXT.en[key] || key;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_match, name) => String(vars[name] ?? ''));
}

function discordIntlLocale(language = DISCORD_DEFAULT_LANGUAGE) {
  const textLanguage = discordTextLanguage(language);
  return DISCORD_INTL_LOCALES[textLanguage] || DISCORD_INTL_LOCALES[DISCORD_DEFAULT_LANGUAGE];
}

function discordTextLocalizations(key) {
  return Object.fromEntries(Object.entries(DISCORD_INTL_LOCALES)
    .filter(([language]) => language !== DISCORD_DEFAULT_LANGUAGE)
    .map(([language, locale]) => [locale, discordText(language, key)]));
}


function discordDisplayCurrency(language = DISCORD_DEFAULT_LANGUAGE) {
  return DISCORD_DISPLAY_CURRENCIES[discordTextLanguage(language)] || DISCORD_DISPLAY_CURRENCIES[DISCORD_DEFAULT_LANGUAGE];
}

function discordDisplayTimeZone(language = DISCORD_DEFAULT_LANGUAGE) {
  return DISCORD_DISPLAY_TIME_ZONES[discordTextLanguage(language)] || DISCORD_DISPLAY_TIME_ZONES[DISCORD_DEFAULT_LANGUAGE];
}


