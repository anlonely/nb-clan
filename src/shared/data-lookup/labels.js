export function normalizeOfficialKdaMetricKey(key = '') {
  return String(key || '')
    .trim()
    .replace(/^(?:raw|rawStats|raw_stats|statistics|stats|data|result|player)[._]/i, '')
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/[^a-zA-Z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .toLowerCase();
}
export function officialKdaExtraGroupIdForKey(key = '') {
  const normalized = normalizeOfficialKdaMetricKey(key);
  if (!normalized) return 'other';
  for (const rule of OFFICIAL_KDA_EXTRA_GROUP_RULES) {
    if (rule.keys?.includes(normalized)) return rule.id;
    if (rule.prefixes?.some((prefix) => normalized.startsWith(prefix))) return rule.id;
    if (rule.includes?.some((part) => normalized.includes(part))) return rule.id;
  }
  return 'other';
}
export function officialKdaExtraGroupTitle(id = 'other', lang = 'zh') {
  const dictionary = OFFICIAL_KDA_EXTRA_GROUP_LABELS[lang] || OFFICIAL_KDA_EXTRA_GROUP_LABELS.en || {};
  const fallbackDictionary = OFFICIAL_KDA_EXTRA_GROUP_LABELS.en || {};
  return dictionary[id] || fallbackDictionary[id] || fallbackDictionary.other || id;
}
